import type { CompareSessionState, WhiteboardOption } from './compareTypes';
import { computeRecommendedDecision, recalculateOptionCost } from './trueCostEngine';

export interface DemoScenarioPreset {
  key: 'product-headphones' | 'service-broadband' | 'travel-goa';
  shortLabel: string;
  session: CompareSessionState;
}

function finalizeDemoSession(
  id: string,
  prompt: string,
  normalizedGoal: string,
  category: CompareSessionState['category'],
  answers: Record<string, string>,
  rawOptions: WhiteboardOption[],
  quarantinedInjections: CompareSessionState['quarantinedInjections']
): CompareSessionState {
  const computed = rawOptions.map((opt) => recalculateOptionCost(opt, opt.addonEnabled));
  const { options, recommendation } = computeRecommendedDecision(computed, answers);
  return {
    id,
    prompt,
    normalizedGoal,
    category,
    answers,
    options,
    recommendation,
    quarantinedInjections,
    openedTabIds: [],
    poweredBy: 'Demo Preset (0 Tokens)',
    executionLayer: 'LAYER_A_STRUCTURED',
    updatedAt: new Date().toISOString(),
  };
}

