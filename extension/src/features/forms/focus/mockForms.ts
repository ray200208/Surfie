// Use the existing persona shape to keep mock mappings limited to actual vault keys.
const personaKeys = new Set<keyof PersonaProfile>(
  Object.keys(DEFAULT_PERSONAS[0]).filter(
    (key): key is keyof PersonaProfile => key !== 'id' && key !== 'label'
  )
);

function matchingVaultKey(key: FocusVaultKey): FocusVaultKey | undefined {
  return personaKeys.has(key) ? key : undefined;
}

